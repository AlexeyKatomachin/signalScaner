package visual;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.stream.Collectors;
import java.util.stream.Stream;

final class IndicatorArtifacts {

    static final Path ROOT = Path.of("target", "indicator-tests");

    private IndicatorArtifacts() {
    }

    static Scenario create(String indicator, String scenario, String dataset, int candleCount) throws IOException {
        Path dir = ROOT.resolve(safe(indicator)).resolve(safe(scenario));
        Files.createDirectories(dir);
        return new Scenario(indicator, scenario, dataset, candleCount, dir);
    }

    static void finish(Scenario scenario,
                       Map<String, Object> context,
                       List<String> resultLines) throws IOException {
        Files.writeString(scenario.context(), toJson(context), StandardCharsets.UTF_8);
        Files.writeString(scenario.result(), String.join(System.lineSeparator(), resultLines) + System.lineSeparator(), StandardCharsets.UTF_8);

        Properties meta = new Properties();
        meta.setProperty("indicator", scenario.indicator);
        meta.setProperty("scenario", scenario.name);
        meta.setProperty("dataset", scenario.dataset);
        meta.setProperty("candles", String.valueOf(scenario.candleCount));
        try (java.io.Writer writer = Files.newBufferedWriter(scenario.meta(), StandardCharsets.UTF_8)) {
            meta.store(writer, "Generated by IndicatorVisualTest");
        }
        rebuildReport();
    }

    static void rebuildReport() throws IOException {
        if (!Files.exists(ROOT)) {
            return;
        }
        List<Path> metas;
        try (Stream<Path> stream = Files.walk(ROOT)) {
            metas = stream.filter(path -> path.getFileName().toString().equals("meta.properties"))
                    .sorted(Comparator.comparing(Path::toString))
                    .collect(Collectors.toList());
        }

        StringBuilder cards = new StringBuilder();
        for (Path metaPath : metas) {
            Properties meta = new Properties();
            try (java.io.Reader reader = Files.newBufferedReader(metaPath, StandardCharsets.UTF_8)) {
                meta.load(reader);
            }
            Path dir = metaPath.getParent();
            String relative = ROOT.relativize(dir).toString().replace('\\', '/');
            String indicator = escapeHtml(meta.getProperty("indicator", ""));
            String scenario = escapeHtml(meta.getProperty("scenario", ""));
            String dataset = escapeHtml(meta.getProperty("dataset", ""));
            String candles = escapeHtml(meta.getProperty("candles", ""));

            cards.append("<section class=\"card\">\n")
                    .append("<div class=\"head\"><div><h2>").append(indicator).append("</h2><h3>")
                    .append(scenario).append("</h3></div><div class=\"meta\">")
                    .append(dataset).append(" · ").append(candles).append(" candles</div></div>\n")
                    .append("<div class=\"compare\"><figure><figcaption>BEFORE</figcaption><a href=\"")
                    .append(relative).append("/before.png\"><img src=\"").append(relative)
                    .append("/before.png\"></a></figure><figure><figcaption>AFTER</figcaption><a href=\"")
                    .append(relative).append("/after.png\"><img src=\"").append(relative)
                    .append("/after.png\"></a></figure></div>\n")
                    .append("<div class=\"links\"><a href=\"").append(relative).append("/context.json\">context.json</a>")
                    .append("<a href=\"").append(relative).append("/result.txt\">result.txt</a></div></section>\n");
        }

        String html = "<!doctype html><html><head><meta charset=\"utf-8\"><title>Indicator validation</title>" +
                "<style>body{font-family:Arial,sans-serif;background:#11131a;color:#eef1f6;margin:0;padding:28px}" +
                "h1{margin:0 0 8px}p{color:#aeb7c6}.card{background:#1a1e28;border:1px solid #2b3342;border-radius:14px;padding:18px;margin:22px 0}" +
                ".head{display:flex;justify-content:space-between;gap:20px;align-items:end}.head h2{margin:0;color:#8fc5ff}.head h3{margin:4px 0 0}.meta{color:#9aa7b8}" +
                ".compare{display:grid;grid-template-columns:1fr 1fr;gap:14px;margin-top:16px}.compare figure{margin:0}.compare img{width:100%;border:1px solid #323b4b;border-radius:8px;background:#121218}" +
                "figcaption{font-size:12px;font-weight:bold;color:#b9c4d3;margin-bottom:6px}.links{display:flex;gap:16px;margin-top:12px}.links a{color:#8fc5ff}" +
                "@media(max-width:900px){.compare{grid-template-columns:1fr}.head{display:block}.meta{margin-top:8px}}</style></head><body>" +
                "<h1>Indicator validation report</h1><p>Every AFTER image uses exactly the same candle set and price scale as BEFORE. " +
                "Use context.json for numeric details and result.txt for the compact summary.</p>" +
                cards + "</body></html>";
        Files.writeString(ROOT.resolve("index.html"), html, StandardCharsets.UTF_8);
    }

    static Map<String, Object> map(Object... keyValues) {
        if (keyValues.length % 2 != 0) {
            throw new IllegalArgumentException("map() requires key/value pairs");
        }
        Map<String, Object> map = new LinkedHashMap<>();
        for (int i = 0; i < keyValues.length; i += 2) {
            map.put(String.valueOf(keyValues[i]), keyValues[i + 1]);
        }
        return map;
    }

    static List<Map<String, Object>> listOfMaps() {
        return new ArrayList<>();
    }

    private static String safe(String value) {
        return value.toLowerCase().replaceAll("[^a-z0-9._-]+", "-").replaceAll("^-|-$", "");
    }

    private static String toJson(Object value) {
        StringBuilder out = new StringBuilder();
        appendJson(out, value, 0);
        return out.append(System.lineSeparator()).toString();
    }

    private static void appendJson(StringBuilder out, Object value, int indent) {
        if (value == null) {
            out.append("null");
        } else if (value instanceof String || value instanceof Character || value instanceof Enum<?>) {
            out.append('"').append(escapeJson(String.valueOf(value))).append('"');
        } else if (value instanceof Number || value instanceof Boolean) {
            out.append(value);
        } else if (value instanceof Map<?, ?>) {
            Map<?, ?> map = (Map<?, ?>) value;
            out.append("{\n");
            int i = 0;
            for (Map.Entry<?, ?> entry : map.entrySet()) {
                indent(out, indent + 2);
                out.append('"').append(escapeJson(String.valueOf(entry.getKey()))).append("\": ");
                appendJson(out, entry.getValue(), indent + 2);
                if (++i < map.size()) out.append(',');
                out.append('\n');
            }
            indent(out, indent);
            out.append('}');
        } else if (value instanceof Collection<?>) {
            Collection<?> values = (Collection<?>) value;
            out.append("[\n");
            int i = 0;
            for (Object item : values) {
                indent(out, indent + 2);
                appendJson(out, item, indent + 2);
                if (++i < values.size()) out.append(',');
                out.append('\n');
            }
            indent(out, indent);
            out.append(']');
        } else {
            out.append('"').append(escapeJson(String.valueOf(value))).append('"');
        }
    }

    private static void indent(StringBuilder out, int spaces) {
        for (int i = 0; i < spaces; i++) out.append(' ');
    }

    private static String escapeJson(String value) {
        return value.replace("\\", "\\\\").replace("\"", "\\\"")
                .replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t");
    }

    private static String escapeHtml(String value) {
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replace("\"", "&quot;");
    }

    static final class Scenario {
        private final String indicator;
        private final String name;
        private final String dataset;
        private final int candleCount;
        private final Path dir;

        private Scenario(String indicator, String name, String dataset, int candleCount, Path dir) {
            this.indicator = indicator;
            this.name = name;
            this.dataset = dataset;
            this.candleCount = candleCount;
            this.dir = dir;
        }

        Path before() {
            return dir.resolve("before.png");
        }

        Path after() {
            return dir.resolve("after.png");
        }

        Path context() {
            return dir.resolve("context.json");
        }

        Path result() {
            return dir.resolve("result.txt");
        }

        Path meta() {
            return dir.resolve("meta.properties");
        }
    }
}
